using System.Globalization;
using System.Text;

namespace Synopio.Engine.Localization;

public static class LanguagesDocument
{
    // Constants
    private const string IssuesUrl = "https://github.com/TripleT3005/Synopio/issues";

    // Fields
    private static readonly (string Category, string Heading)[] Categories =
    [
        ("standard", "Standard languages / Standardsprachen"),
        ("dialect", "Dialects / Dialekte"),
        ("fun", "Fun languages / Spaßsprachen"),
    ];

    // Methods
    public static string Generate(IEnumerable<LanguageFile> languages)
    {
        ArgumentNullException.ThrowIfNull(languages);

        var sorted = languages.OrderBy(language => language.Code, StringComparer.Ordinal).ToList();
        var builder = new StringBuilder();
        builder.Append(
            $"""
            # Languages

            [English](#english) · [Deutsch](#deutsch)

            ## English

            All translations were generated by Claude (AI). Files that a person has checked name the reviewer in the table and in the file itself. If you notice a mistake or know a better wording, please open an [issue]({IssuesUrl}) or a pull request; reviewers are credited with their GitHub name if they agree.

            The codes follow [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO 639 language codes, ISO 3166 regions and ISO 15924 scripts. Dialects use their ISO 639-3 code where one exists, everything else a private-use code with `-x-`. Dialects and fun languages are only offered in the language list, never chosen automatically. Missing texts fall back to the language named in the file, otherwise to English.

            This list is generated from the headers of the files in [`lang`](lang). After changing them, run `$env:UPDATE_LANGUAGES = 1; dotnet test --project Synopio.Engine.Tests` to update it; the CI fails if it is out of date.

            ## Deutsch

            Alle Übersetzungen wurden von Claude (KI) erzeugt. Dateien, die eine Person geprüft hat, nennen die prüfende Person in der Tabelle und in der Datei selbst. Wenn dir ein Fehler auffällt oder du eine bessere Formulierung kennst, eröffne gern ein [Issue]({IssuesUrl}) oder einen Pull Request; mit Einverständnis wird die prüfende Person mit ihrem GitHub-Namen genannt.

            Die Codes folgen [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO-639-Sprachcodes, ISO-3166-Regionen und ISO-15924-Schriften. Dialekte nutzen ihren ISO-639-3-Code, sofern es einen gibt, alles andere einen Private-Use-Code mit `-x-`. Dialekte und Spaßsprachen werden nur in der Sprachauswahl angeboten, nie automatisch gewählt. Fehlende Texte fallen auf die in der Datei genannte Sprache zurück, sonst auf Englisch.

            Diese Liste wird aus den Köpfen der Dateien in [`lang`](lang) erzeugt. Nach Änderungen daran aktualisiert `$env:UPDATE_LANGUAGES = 1; dotnet test --project Synopio.Engine.Tests` sie; die CI schlägt fehl, wenn sie veraltet ist.

            """);

        foreach (var (category, heading) in Categories)
        {
            var entries = sorted.Where(language => string.Equals(language.Category, category, StringComparison.OrdinalIgnoreCase)).ToList();
            if (entries.Count == 0)
            {
                continue;
            }

            builder.Append(CultureInfo.InvariantCulture, $"\n## {heading}\n\n");
            builder.Append("| Code | Language | Name in the language list | Reviewed by |\n");
            builder.Append("|---|---|---|---|\n");

            foreach (var language in entries)
            {
                var reviewers = language.Reviewers.Count == 0
                    ? "–"
                    : string.Join(", ", language.Reviewers.Select(reviewer => $"[@{reviewer}](https://github.com/{reviewer})"));
                builder.Append(CultureInfo.InvariantCulture, $"| `{language.Code}` | {language.EnglishName} | {language.Name} | {reviewers} |\n");
            }
        }

        return builder.ToString();
    }
}
